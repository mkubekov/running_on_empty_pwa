/**
 * «Листы Изменений» из главы 7 в декларативном виде.
 *
 * Автор настаивает: осваивать по одному навыку, максимум два одновременно,
 * и в том порядке, в котором они идут в книге. Отсюда поле `order` и лимит
 * активных листов в интерфейсе.
 *
 * Добавить оставшиеся листы = дописать объект сюда, движок уже умеет их
 * рисовать по полю `type`.
 */

export type TrackerType =
  /** Счётчик за день: сколько раз отказал, сколько раз попросил помощи. */
  | { kind: 'counter'; unit: string; hint: string }
  /** Несколько групп по N пунктов: Программа Трёх Дел. */
  | {
      kind: 'checklist'
      groups: {
        id: string
        title: string
        slots: number
        placeholder: string
      }[]
    }
  /** Накопительный список без привязки к дню: люблю / не люблю. */
  | { kind: 'list'; buckets: { id: string; title: string }[] }
  /** Оценка по шкале: сегодня отдыхал мало ↔ слишком много. */
  | {
      kind: 'scale'
      min: number
      max: number
      minLabel: string
      maxLabel: string
    }
  /** Простая отметка «сегодня получилось» + заметка. */
  | { kind: 'habit'; hint: string }

export interface TrackerDef {
  id: string
  title: string
  chapterRef: string
  /** Зачем это нужно — своими словами, 2–3 предложения. */
  intro: string
  order: number
  type: TrackerType
  /** Движок умеет рисовать этот тип. Нереализованные нельзя включить. */
  implemented: boolean
}

